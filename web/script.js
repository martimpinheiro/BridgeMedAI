// Simulator state and UI
const simulator = {
    step: 1,
    statuses: {
        frontend: 'pending',
        backend: 'pending',
        database: 'pending',
        llm: 'pending',
        human: 'pending',
        docs: 'pending'
    },
    preValidation: null,
    draft: null,
    logs: []
};

function renderStatusCards() {
    const grid = document.getElementById('sim-status-grid');
    if (!grid) return;
    const cards = [
        {key: 'frontend', label: 'Frontend (UI)'} ,
        {key: 'backend', label: 'Backend (API)'} ,
        {key: 'database', label: 'Database'} ,
        {key: 'llm', label: 'LLM / Drafting'} ,
        {key: 'human', label: 'Revisor Humano'} ,
        {key: 'docs', label: 'Documentos'}
    ];
    grid.innerHTML = cards.map(c => `
        <div class="status-card status-${simulator.statuses[c.key]}">
            <div class="status-title">${c.label}</div>
            <div class="status-value">${simulator.statuses[c.key]}</div>
        </div>
    `).join('');
}

function appendLog(html) {
    simulator.logs.push(html);
    const logsEl = document.getElementById('sim-logs');
    if (!logsEl) return;
    logsEl.innerHTML = simulator.logs.join('\n');
    logsEl.scrollTop = logsEl.scrollHeight;
}

function goToStep(n) {
    simulator.step = n;
    document.querySelectorAll('.sim-btn').forEach(btn => btn.classList.remove('active'));
    const btn = document.getElementById(`step${n}-btn`);
    if (btn) btn.classList.add('active');
    renderStatusCards();
    // Show appropriate controls
    document.getElementById('export-btn').style.display = (n === 5 && simulator.statuses.docs === 'complete') ? 'inline-block' : 'none';
}

function resetSim() {
    simulator.step = 1;
    simulator.statuses = {frontend:'pending', backend:'pending', database:'pending', llm:'pending', human:'pending', docs:'pending'};
    simulator.preValidation = null;
    simulator.draft = null;
    simulator.logs = [];
    document.getElementById('sim-draft').innerHTML = '';
    document.getElementById('export-btn').style.display = 'none';
    goToStep(1);
    appendLog('<div class="chat-ai">Simulator reset.</div>');
}

function nextStep() {
    const s = simulator.step;
    if (s === 1) return simulateSubmit();
    if (s === 2) return simulatePreValidation();
    if (s === 3) return promptHumanReview();
    if (s === 4) return simulatePrefill();
    if (s === 5) return finalizeAndShow();
}

function prevStep() {
    if (simulator.step > 1) {
        goToStep(simulator.step - 1);
    }
}

function simulateSubmit() {
    appendLog(`<div class="chat-user">Usuário</div><div class="chat-text">Submeteu novo projeto: <strong>ThermoAI</strong></div>`);
    simulator.statuses.frontend = 'complete';
    renderStatusCards();
    simulator.step = 2;
    goToStep(2);
}

function simulatePreValidation() {
    appendLog(`<div class="chat-ai">BridgeMedAI Core</div><div class="chat-text">A correr pré-validação automática...</div>`);
    simulator.statuses.backend = 'inprogress';
    renderStatusCards();
    // Simulate async checks
    setTimeout(() => {
        simulator.preValidation = {
            findings: [
                {field: 'Classificação MDR', suggestion: 'Classe I (medição) — OK'},
                {field: 'AI Risk', suggestion: 'Alto risco — exigir registros e supervisão humana'},
                {field: 'Gestão de Risco', suggestion: 'Mapa de riscos com 3 itens pendentes'}
            ]
        };
        simulator.statuses.backend = 'complete';
        simulator.statuses.database = 'complete';
        appendLog('<div class="chat-ai">Pré-validação concluída. Resultados provisórios disponíveis.</div>');
        // show summary and confirm/correct controls
        renderPrevalSummary();
    }, 1000);
}

function renderPrevalSummary() {
    const logsEl = document.getElementById('sim-logs');
    let html = '<div class="chat-block"><div class="chat-ai">Pré-validação — Resultados</div>';
    html += '<div class="chat-text"><ul>' + simulator.preValidation.findings.map(f => `<li><strong>${f.field}:</strong> ${f.suggestion}</li>`).join('') + '</ul></div>';
    html += `<div class="sim-action-row"><button class="btn btn-primary" onclick="confirmPreval()">Confirmar</button> <button class="btn btn-secondary" onclick="correctPreval()">Corrigir</button></div></div>`;
    appendLog(html);
}

function confirmPreval() {
    appendLog('<div class="chat-user">Especialista</div><div class="chat-text">Confirmado os resultados da pré-validação.</div>');
    simulator.statuses.human = 'complete';
    renderStatusCards();
    // advance to prefill
    simulator.step = 4;
    goToStep(4);
}

function correctPreval() {
    const correction = prompt('Insira correção ou notas do especialista:', 'AI Risk: Médio');
    if (correction !== null) {
        appendLog(`<div class="chat-user">Especialista</div><div class="chat-text">Correção aplicada: ${escapeHtml(correction)}</div>`);
        simulator.preValidation.findings.push({field:'Especialista', suggestion: correction});
        simulator.statuses.human = 'complete';
        renderStatusCards();
        simulator.step = 4;
        goToStep(4);
    }
}

function simulatePrefill() {
    appendLog('<div class="chat-ai">Gerando rascunho documental com base nas evidências...</div>');
    simulator.statuses.llm = 'inprogress';
    renderStatusCards();
    setTimeout(() => {
        simulator.draft = `Rascunho técnico inicial para ThermoAI:\n- Classificação: Classe I (medição)\n- Risco AI: Alto (recomenda-se supervisão humana)\n- Requisitos: ISO 13485, ISO 14971\n`;
        document.getElementById('sim-draft').innerText = simulator.draft;
        simulator.statuses.llm = 'complete';
        simulator.statuses.docs = 'inprogress';
        appendLog('<div class="chat-ai">Rascunho gerado. Por favor, proceda à verificação final.</div>');
        renderStatusCards();
        simulator.step = 5;
        goToStep(5);
    }, 1200);
}

function promptHumanReview() {
    // This step is handled via confirmPreval / correctPreval triggered from preval summary
    appendLog('<div class="chat-ai">Aguardando revisão humana. Use "Confirmar" ou "Corrigir" quando disponível.</div>');
}

function finalizeAndShow() {
    appendLog('<div class="chat-ai">Verificação final em curso...</div>');
    simulator.statuses.docs = 'complete';
    renderStatusCards();
    document.getElementById('sim-draft').innerText = simulator.draft || '—';
    document.getElementById('export-btn').style.display = 'inline-block';
}

function exportDoc() {
    const payload = {
        project: 'ThermoAI',
        preValidation: simulator.preValidation,
        draft: simulator.draft,
        timestamps: new Date().toISOString()
    };
    const blob = new Blob([JSON.stringify(payload, null, 2)], {type: 'application/json'});
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'thermoai-documentation.json';
    document.body.appendChild(a);
    a.click();
    a.remove();
    URL.revokeObjectURL(url);
    appendLog('<div class="chat-ai">Documento exportado.</div>');
}

function escapeHtml(unsafe) {
    return unsafe.replace(/[&<>"']/g, function(m) { return {'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":"&#39;"}[m]; });
}

